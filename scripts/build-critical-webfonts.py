#!/usr/bin/env python3
"""Share two small, exact-outline first-use fonts between UI and chart text.

Existing complete fonts remain available for arbitrary user text. Their CSS
unicode ranges exclude the critical characters, so one character has only one
font resource per face. No canonical OTF or scientific typography is changed.
Run after either base font builder, using font-delivery-requirements.txt.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import tempfile
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

spec = importlib.util.spec_from_file_location("base_fonts", Path(__file__).with_name("build-webfonts.py"))
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
ROOT, FONT_ROOT = base.ROOT, base.FONT_ROOT
MANIFEST = FONT_ROOT / "critical-manifest.json"


def authored_points():
    files = sorted(p for p in (ROOT / "web/src").rglob("*")
                   if p.suffix in {".ts", ".tsx", ".json"}
                   and ".test." not in p.name and "evidence" not in p.parts)
    # Include the browser-generated list marker, absent from authored text.
    return set(range(32, 127)) | {0x2022} | {ord(c) for p in files for c in p.read_text()}


def verify_face(record):
    source = base.SOURCE_ROOT / record["source"]
    assert base.sha(source) == record["sourceSha256"], "Canonical font changed"
    file = FONT_ROOT / record["file"]
    assert base.sha(file) == record["sha256"], "Critical font hash mismatch"
    with TTFont(source) as original, TTFont(file) as font:
        assert set(font.getBestCmap()) == set(record["codepoints"])
        assert base.face_metadata(original, record["fontWeight"], "normal") == base.face_metadata(font, record["fontWeight"], "normal")
        for table, fields in [("head", ["unitsPerEm"]), ("hhea", ["ascent", "descent", "lineGap"]),
                              ("OS/2", ["sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"])]:
            assert all(getattr(original[table], f) == getattr(font[table], f) for f in fields)
        before, after = original.getGlyphSet(), font.getGlyphSet()
        for glyph in font.getGlyphOrder():
            for table in ["hmtx", "vmtx"]:
                assert original[table].metrics[glyph] == font[table].metrics[glyph]
            a, b = RecordingPen(), RecordingPen()
            before[glyph].draw(a); after[glyph].draw(b)
            assert a.value == b.value, f"Glyph outline changed: {glyph}"


def rule(family, weight, style, file, points):
    return (f"@font-face{{font-family:'{family}';src:url('/fonts/{file}') format('woff2');"
            f"font-weight:{weight};font-style:{style};font-display:swap;unicode-range:{base.ranges(sorted(points))};}}")


def delivery_css(records):
    fonts = json.loads((FONT_ROOT / "webfont-manifest.json").read_text())["fonts"]
    critical = {r["fontId"]: r for r in records}
    css = ["/* Generated by scripts/build-critical-webfonts.py; complete OFL faces with shared first-use subsets. */"]
    for face in fonts:
        fast = critical.get(face["fontId"])
        selected = set(fast["codepoints"]) if fast else set()
        covered = set(selected)
        if fast:
            css.append(rule(face["family"], face["fontWeight"], "normal", fast["file"], selected))
        for shard in face["shards"]:
            effective = set(shard["codepoints"]) - selected
            assert not covered & effective, "Overlapping effective unicode ranges"
            covered.update(effective)
            if effective:
                css.append(rule(face["family"], face["fontWeight"], face.get("fontStyle", "normal"), shard["file"], effective))
        assert covered == {cp for s in face["shards"] for cp in s["codepoints"]}, "Full font coverage lost"
    ui = ["/* Generated by scripts/build-critical-webfonts.py; UI and figures share the same pinned glyphs and URLs. */"]
    for face in json.loads((FONT_ROOT / "ui/manifest.json").read_text()):
        fast = next((r for r in records if r["source"] == face["source"]), None)
        with TTFont(FONT_ROOT / "ui" / face["file"]) as font:
            points = set(font.getBestCmap())
        if fast:
            ui.append(rule(face["family"], face["weight"], "normal", fast["file"], fast["codepoints"]))
            points -= set(fast["codepoints"])
        if points:
            ui.append(rule(face["family"], face["weight"], "normal", "ui/" + face["file"], points))
    return "\n".join(css) + "\n", "\n".join(ui) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    points = authored_points()
    sources = json.loads((base.SOURCE_ROOT / "manifest.json").read_text())
    if args.check:
        records = json.loads(MANIFEST.read_text())["faces"]
    else:
        records = []
        with tempfile.TemporaryDirectory(prefix='openacad-critical-') as directory:
            for source, stem, family, weight, style in base.FONTS:
                if family != "Noto Sans SC" or style != "normal":
                    continue
                assert base.sha(base.SOURCE_ROOT / source) == sources[source]
                with TTFont(base.SOURCE_ROOT / source) as font:
                    selected = sorted(points & set(font.getBestCmap()))
                record = base.create_shard((source, stem, family, weight, style, 'critical', selected, directory))
                destination = FONT_ROOT / record["file"]
                destination.write_bytes((Path(directory) / destination.name).read_bytes())
                record.update(source=source, sourceSha256=sources[source])
                records.append(record)
    for record in records:
        assert record['sourceSha256'] == sources[record['source']], 'Critical font must use the pinned canonical source'
        with TTFont(base.SOURCE_ROOT / record['source']) as font:
            assert points & set(font.getBestCmap()) <= set(record['codepoints']), 'Authored text needs regenerated critical fonts'
        verify_face(record)
    css, ui = delivery_css(records)
    outputs = {ROOT / 'web/src/styles/font-faces.css': css,
               ROOT / 'web/src/styles/ui-font-faces.css': ui}
    if args.check:
        for file, value in outputs.items():
            assert file.read_text() == value, f'Font delivery CSS out of date: {file}'
    else:
        for file, value in outputs.items():
            file.write_text(value)
        MANIFEST.write_text(json.dumps({'schemaVersion': 1, 'strategy': 'shared UI/chart authored-text subsets; disjoint complete fallback ranges', 'faces': records}, ensure_ascii=False, indent=2) + '\n')
        keep = {Path(r['file']).name for r in records}
        for file in (FONT_ROOT / 'woff2').glob('*-critical.*.woff2'):
            if file.name not in keep:
                file.unlink()
    print(json.dumps({'passed': True, 'criticalBytes': sum(r['bytes'] for r in records),
                      'faces': [{k: r[k] for k in ['file', 'bytes', 'fontWeight']} for r in records],
                      'outlinesAndMetrics': 'identical to pinned OTFs', 'completeCoverage': True}))


if __name__ == '__main__':
    main()
